#!/usr/bin/env bun
/**
 * generate-static-pages — Auto-generate page.static.tsx for all dynamic routes.
 *
 * For each [param] route, generates a page.static.tsx that:
 *   1. Exports generateStaticParams() returning []
 *   2. Reads params from ?key=value (query string) via useRouteParams()
 *   3. Dynamically imports the original page's content component
 *
 * The developer needs to extract their page content into a separate
 * client component file (page-content.tsx) that accepts params as props.
 * If page-content.tsx doesn't exist, a redirect fallback is generated instead.
 *
 * Usage:
 *   bun scripts/generate-static-pages.ts [options]
 *
 * Options:
 *   --dry-run    Show what would be generated without writing files
 *   --force      Overwrite existing page.static.tsx files
 *   --help       Show this help message
 */

import { existsSync, writeFileSync, readFileSync, readdirSync, statSync } from "fs";
import { join, relative, dirname, basename } from "path";

const ROOT = join(import.meta.dir, "..");
const APP_DIR = join(ROOT, "app");

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const force = args.includes("--force");
if (args.includes("--help")) {
  console.log(`
  generate-static-pages — Auto-generate page.static.tsx for dynamic routes

  Usage:  bun scripts/generate-static-pages.ts [options]

  Options:
    --dry-run    Show what would be generated without writing files
    --force      Overwrite existing page.static.tsx files
    --help       Show this help message

  For each dynamic route ([param]), generates page.static.tsx that reads
  params from query string (?param=value) for static export compatibility.

  If a page-content.tsx exists in the same directory, it will be imported
  and rendered with params from the query string.
  Otherwise, a redirect fallback is generated.
  `);
  process.exit(0);
}

// ─── Helpers ────────────────────────────────────────────────────────────────

function findFilesRecursive(dir: string, match: (name: string) => boolean): string[] {
  const results: string[] = [];
  if (!existsSync(dir)) return results;
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      results.push(...findFilesRecursive(full, match));
    } else if (match(entry)) {
      results.push(full);
    }
  }
  return results;
}

/** Extract [paramName] segments from a path */
function extractParams(filePath: string): string[] {
  const matches = filePath.match(/\[([a-zA-Z]+)\]/g);
  if (!matches) return [];
  return matches.map((m) => m.slice(1, -1));
}

/** Find the nearest non-dynamic parent route */
function findParentRoute(filePath: string): string {
  const parts = relative(APP_DIR, dirname(filePath)).split("/");
  const staticParts: string[] = [];
  for (const part of parts) {
    if (part.includes("[")) break;
    // Skip route groups like (app)
    if (part.startsWith("(") && part.endsWith(")")) continue;
    staticParts.push(part);
  }
  return "/" + staticParts.join("/") || "/";
}

function rel(p: string) { return relative(ROOT, p); }

// ─── Find dynamic pages ────────────────────────────────────────────────────

const allPages = findFilesRecursive(APP_DIR, (n) => n === "page.tsx" || n === "page.ts");
const dynamicPages = allPages.filter((p) => p.includes("["));

console.log(`
📄 generate-static-pages${dryRun ? " (dry run)" : ""}
   Found ${dynamicPages.length} dynamic route page(s)
`);

let created = 0;
let skipped = 0;

for (const pagePath of dynamicPages) {
  const dir = dirname(pagePath);
  const ext = pagePath.endsWith(".ts") ? "ts" : "tsx";
  const staticPath = join(dir, `page.static.${ext}`);
  const contentPath = join(dir, `page-content.tsx`);
  const params = extractParams(pagePath);
  const parentRoute = findParentRoute(pagePath);

  if (existsSync(staticPath) && !force) {
    console.log(`  · ${rel(staticPath)} — exists (skip, use --force to overwrite)`);
    skipped++;
    continue;
  }

  const hasContent = existsSync(contentPath);

  const paramType = `{ ${params.map((p) => `${p}: string`).join("; ")} }`;

  let code: string;
  if (hasContent) {
    code = `// Auto-generated by generate:static — do not edit
import { Suspense } from "react";
import Content from "./page-content-static";

export function generateStaticParams() { return []; }
export const dynamicParams = false;

export default function StaticPage() {
  return <Suspense><Content /></Suspense>;
}
`;
    const wrapperPath = join(dir, "page-content-static.tsx");
    const wrapperCode = `"use client";
import { useRouteParams } from "@/lib/use-route-params";
import PageContent from "./page-content";

export default function Wrapper() {
  const params = useRouteParams<${paramType}>();
${params.map((p) => `  const ${p} = params.${p};`).join("\n")}
  if (${params.map((p) => `!${p}`).join(" || ")}) return null;
  return <PageContent ${params.map((p) => `${p}={${p}}`).join(" ")} />;
}
`;
    if (!dryRun) writeFileSync(wrapperPath, wrapperCode);
  } else {
    code = `// Auto-generated by generate:static — do not edit
import { Suspense } from "react";
import Fallback from "./static-fallback";

export function generateStaticParams() { return []; }
export const dynamicParams = false;

export default function StaticPage() {
  return <Suspense><Fallback /></Suspense>;
}
`;
    const fallbackPath = join(dir, "static-fallback.tsx");
    const fallbackCode = `"use client";
import { useEffect } from "react";
import { useRouter } from "next/navigation";
import { useRouteParams } from "@/lib/use-route-params";

export default function StaticFallback() {
  const router = useRouter();
  const params = useRouteParams<${paramType}>();
${params.map((p) => `  const ${p} = params.${p};`).join("\n")}

  useEffect(() => {
    if (${params.map((p) => `!${p}`).join(" && ")}) {
      router.replace("${parentRoute}");
    }
  }, [${params.join(", ")}, router]);

  if (${params.map((p) => `!${p}`).join(" && ")}) return null;

  return (
    <div className="flex h-full items-center justify-center text-muted-foreground text-sm p-4 text-center">
      <p>This page requires a server. Open in browser to access.</p>
    </div>
  );
}
`;
    if (!dryRun) writeFileSync(fallbackPath, fallbackCode);
  }

  if (dryRun) {
    console.log(`  ${hasContent ? "✦" : "○"} ${rel(staticPath)} — ${hasContent ? "with page-content.tsx" : "redirect fallback"} (params: ${params.join(", ")})`);
  } else {
    writeFileSync(staticPath, code);
    console.log(`  ${hasContent ? "✦" : "○"} ${rel(staticPath)} — ${hasContent ? "with page-content.tsx" : "redirect fallback"}`);
  }
  created++;
}

console.log(`
  ${created} generated, ${skipped} skipped
${!dryRun && created > 0 ? `
  Next steps:
  1. For full static support, extract page content into page-content.tsx
  2. Use useRouteParams() hook to read params in your components
  3. Run \`bun run build:static\` to build
` : ""}
`);
