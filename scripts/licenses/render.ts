// Plain-text rendering of the notices (public/legal/THIRD_PARTY_NOTICES.txt): one block per package, then each
// distinct license text once, with the packages that use it. Deterministic, like the JSON.
import type { NoticeEntry, NoticesFile } from "@/lib/licenses/types";

const RULE = "=".repeat(80);
const THIN = "-".repeat(80);

function label(e: NoticeEntry): string {
  return e.version ? `${e.name}@${e.version}` : e.name;
}

function origin(e: NoticeEntry): string {
  switch (e.source) {
    case "npm":
      return "npm package";
    case "inlined":
      return `Bundled inside ${e.via ?? "another package"}`;
    case "vendored":
      return `Vendored inside ${e.via ?? "another package"}`;
    case "asset":
      return `Asset (${e.via ?? "bundled"})`;
  }
}

export function renderNoticesText(file: NoticesFile): string {
  const lines: string[] = [
    "THIRD-PARTY SOFTWARE NOTICES",
    "",
    "Merchiva includes the third-party software listed below. Each entry names the software, the license",
    "Merchiva uses it under and its copyright notices. The full license texts follow in the second part and",
    "are referenced as [T<id>].",
    "",
    `Entries: ${file.packageCount}`,
    "Generated by scripts/licenses/generate.ts. Do not edit by hand.",
    "",
    RULE,
    "PART 1: SOFTWARE",
    RULE,
  ];
  const usedBy = new Map<string, string[]>();
  for (const e of file.packages) {
    lines.push("", `${label(e)}  (${e.license})`);
    lines.push(`  ${origin(e)}`);
    if (e.elected) lines.push(`  Used under: ${e.elected}`);
    if (e.repository) lines.push(`  Repository: ${e.repository}`);
    for (const c of e.copyright) lines.push(`  ${c}`);
    if (e.note) lines.push(`  Note: ${e.note}`);
    if (e.textIds.length > 0) lines.push(`  License text: ${e.textIds.map((id) => `[T${id}]`).join(", ")}`);
    for (const id of e.textIds) {
      const list = usedBy.get(id) ?? [];
      list.push(e.source === "npm" ? label(e) : `${e.name} (${e.via ?? e.source})`);
      usedBy.set(id, list);
    }
  }
  lines.push("", RULE, "PART 2: LICENSE TEXTS", RULE);
  for (const [id, text] of Object.entries(file.texts)) {
    lines.push("", `[T${id}]`, `Used by: ${(usedBy.get(id) ?? []).join(", ")}`, THIN, text);
  }
  return `${lines.join("\n")}\n`;
}
