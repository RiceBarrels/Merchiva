"use client";

import { useMemo, useState } from "react";
import { formatTs, sqlString } from "@/lib/merchiva-admin/client";
import { DataTable, ErrorBanner, Notice, Panel, btnGhostCls, inputCls, type Column } from "@/components/merchiva-admin/ui";
import { useAdminQuery } from "@/components/merchiva-admin/use-admin-query";
import { Mono, NoOrg, Pager, truncate, usePaged } from "./shared";

interface DailyBriefingRow {
  id: string;
  organizationId: string;
  date: string;
  content: string;
  summary: string | null;
  generatedBy: string;
  generatedAt: number;
  actions: string | null;
}

function prettyJson(raw: string | null): string | null {
  if (!raw) return null;
  try {
    return JSON.stringify(JSON.parse(raw), null, 2);
  } catch {
    return raw;
  }
}

export function BriefingsTab({ orgId }: { orgId: string | null }) {
  const briefings = useAdminQuery<DailyBriefingRow>(orgId ? `SELECT * FROM daily_briefing WHERE organization_id = ${sqlString(orgId)}` : null);
  const [search, setSearch] = useState("");
  const [openId, setOpenId] = useState<string | null>(null);

  const sorted = useMemo(() => {
    const q = search.trim().toLowerCase();
    return [...briefings.rows]
      .filter((b) => !q || b.date.includes(q) || b.content.toLowerCase().includes(q) || (b.summary ?? "").toLowerCase().includes(q) || b.generatedBy.toLowerCase().includes(q))
      .sort((a, b) => {
        if (a.date !== b.date) return a.date < b.date ? 1 : -1;
        return b.generatedAt - a.generatedAt;
      });
  }, [briefings.rows, search]);
  const paged = usePaged(sorted, 50);
  const open = openId ? briefings.rows.find((b) => b.id === openId) ?? null : null;

  if (!orgId) return <NoOrg what="daily briefings" />;

  const columns: Column<DailyBriefingRow>[] = [
    { key: "date", header: "Date", className: "whitespace-nowrap font-mono", render: (b) => b.date },
    { key: "generatedBy", header: "Generated by", className: "whitespace-nowrap font-mono text-[11px] text-stone-600", render: (b) => b.generatedBy },
    { key: "generatedAt", header: "Generated at", className: "whitespace-nowrap text-stone-600", render: (b) => formatTs(b.generatedAt) },
    {
      key: "summary",
      header: "Summary / content",
      render: (b) => (
        <div className="max-w-[620px]">
          {b.summary && <div className="font-medium">{truncate(b.summary, 140)}</div>}
          <div className="text-stone-600">{truncate(b.content, 160)}</div>
        </div>
      ),
    },
    { key: "size", header: "Size", className: "whitespace-nowrap font-mono text-[11px] text-stone-600", render: (b) => `${b.content.length.toLocaleString()} ch` },
    { key: "id", header: "Id", render: (b) => <Mono value={b.id} /> },
    {
      key: "actions",
      header: "",
      className: "text-right",
      render: (b) => (
        <button type="button" className={btnGhostCls} onClick={() => setOpenId(b.id === openId ? null : b.id)}>
          {b.id === openId ? "Close" : "View"}
        </button>
      ),
    },
  ];

  return (
    <div className="space-y-4">
      <Panel
        title={`Daily briefings (${briefings.rows.length})`}
        actions={
          <>
            <input className={`${inputCls} w-56`} placeholder="Filter by date / text" value={search} onChange={(e) => setSearch(e.target.value)} />
            <button type="button" className={btnGhostCls} onClick={() => briefings.reload()}>
              Refresh
            </button>
          </>
        }
      >
        <ErrorBanner message={briefings.error} />
        <Notice message="Read-only: the module has no reducer to delete a briefing." />
        <DataTable columns={columns} rows={paged.slice} loading={briefings.loading} empty="No briefings for this org" rowKey={(b) => b.id} />
        <Pager page={paged.page} pageCount={paged.pageCount} total={paged.total} pageSize={paged.pageSize} onChange={paged.setPage} label="briefings" />
      </Panel>

      {open && (
        <Panel
          title={`Briefing ${open.date} · ${open.generatedBy}`}
          actions={
            <button type="button" className={btnGhostCls} onClick={() => setOpenId(null)}>
              Close
            </button>
          }
        >
          <div className="grid gap-4 p-4 lg:grid-cols-[2fr_1fr]">
            <div>
              {open.summary && (
                <>
                  <div className="mb-1 font-mono text-[11px] uppercase tracking-wider text-stone-500">Summary</div>
                  <div className="mb-4 whitespace-pre-wrap text-[13px]">{open.summary}</div>
                </>
              )}
              <div className="mb-1 font-mono text-[11px] uppercase tracking-wider text-stone-500">Content</div>
              <pre className="max-h-[520px] overflow-auto whitespace-pre-wrap break-words rounded-[0.15rem] border border-stone-200 bg-stone-50 p-3 font-mono text-[12px]">{open.content}</pre>
            </div>
            <div className="space-y-4">
              <div>
                <div className="mb-1 font-mono text-[11px] uppercase tracking-wider text-stone-500">Actions</div>
                <pre className="max-h-[240px] overflow-auto whitespace-pre-wrap break-words rounded-[0.15rem] border border-stone-200 bg-stone-50 p-3 font-mono text-[11px]">
                  {prettyJson(open.actions) ?? "—"}
                </pre>
              </div>
              <div className="text-[12px] text-stone-600">
                <div>
                  Generated {formatTs(open.generatedAt)} by <span className="font-mono">{open.generatedBy}</span>
                </div>
                <div>
                  Id <Mono value={open.id} />
                </div>
              </div>
            </div>
          </div>
        </Panel>
      )}
    </div>
  );
}
