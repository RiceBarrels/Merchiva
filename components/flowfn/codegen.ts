import { NODE_LIB, safeIdent } from "./node-lib";
import type { FlowFunction, FlowNode, GeneratedCode, ExecutionResult } from "./types";

export function generateCode(fn: FlowFunction, allFns: FlowFunction[] = []): GeneratedCode {
  const nodesById: Record<string, FlowNode> = {};
  fn.nodes.forEach((n) => (nodesById[n.id] = n));

  const returnNode = fn.nodes.find((n) => n.type === "return");
  const params = fn.nodes
    .filter((n) => n.type === "param")
    .sort((a, b) => (a.y - b.y) || (a.x - b.x));

  const incoming: Record<string, { node: string; port: string }> = {};
  fn.edges.forEach((e) => {
    incoming[e.to.node + "|" + e.to.port] = e.from;
  });

  const memo = new Map<string, string>();
  const visiting = new Set<string>();
  let currentIterName: string | null = null;

  const ctx = {
    fnExists: (name: string) => allFns.some((f) => f.name === name && f.id !== fn.id),
    isConnected: (nodeId: string, port: string) => !!incoming[nodeId + "|" + port],
    exprWithIterator: (nodeId: string, portId: string, iterName: string, fallbackExpr: string) => {
      const src = incoming[nodeId + "|" + portId];
      if (!src) return fallbackExpr;
      const prevIter = currentIterName;
      currentIterName = iterName;
      try {
        return resolveOutput(src.node, src.port);
      } finally {
        currentIterName = prevIter;
      }
    },
  };

  function resolveInput(nodeId: string, port: string): string | undefined {
    const src = incoming[nodeId + "|" + port];
    if (!src) return undefined;
    return resolveOutput(src.node, src.port);
  }

  function resolveOutput(nodeId: string, portId: string): string {
    const node = nodesById[nodeId];
    if (!node) return "undefined";
    const def = NODE_LIB[node.type];
    if (!def) return "undefined";
    const memoKey = node.id + "|" + portId + "|" + (currentIterName || "");
    if (memo.has(memoKey)) return memo.get(memoKey)!;
    if (visiting.has(memoKey)) return "/*cycle*/undefined";
    visiting.add(memoKey);

    const get = (port: string, fallback = "undefined") => {
      const v = resolveInput(node.id, port);
      return v === undefined ? fallback : v;
    };
    let expr = "undefined";
    if (typeof def.expr === "function") {
      expr = def.expr(node, get, ctx);
    }
    visiting.delete(memoKey);
    memo.set(memoKey, expr);
    return expr;
  }

  const isAsync = fn.nodes.some((n) => NODE_LIB[n.type]?.async);
  const paramList = params.map((p) => safeIdent(p.data.name as string)).join(", ");

  const used = new Set<string>();
  function markUsed(nodeId: string) {
    if (used.has(nodeId)) return;
    used.add(nodeId);
    fn.edges.filter((e) => e.to.node === nodeId).forEach((e) => markUsed(e.from.node));
  }
  if (returnNode) markUsed(returnNode.id);

  const sideStmts: string[] = [];
  fn.nodes.forEach((n) => {
    const def = NODE_LIB[n.type];
    if (def?.side && !used.has(n.id)) {
      const exprStr = resolveOutput(n.id, def.outputs[0]?.id || "out");
      sideStmts.push(`  ${exprStr};`);
    }
  });

  let returnExpr = "undefined";
  if (returnNode) {
    const v = resolveInput(returnNode.id, "value");
    if (v !== undefined) returnExpr = v;
  }

  const asyncKw = isAsync ? "async " : "";
  const fnName = safeIdent(fn.name || "myFn");
  const body = [...sideStmts, `  return ${returnExpr};`].join("\n");
  const code = `${asyncKw}function ${fnName}(${paramList}) {\n${body}\n}`;

  return {
    code,
    isAsync,
    fnName,
    paramList: params.map((p) => ({
      name: safeIdent(p.data.name as string),
      type: (p.data.type as string) || "any",
    })),
  };
}

export function generateAllCode(fns: FlowFunction[]): string {
  const head = `// Generated by FlowFn — ${new Date().toLocaleString()}\n// ${fns.length} function${fns.length === 1 ? "" : "s"}\n\n`;
  return head + fns.map((f) => generateCode(f, fns).code).join("\n\n");
}

export async function executeFunction(fn: FlowFunction, args: string[], allFns: FlowFunction[]): Promise<ExecutionResult> {
  const logs: { label: string; value: unknown }[] = [];
  const __log = (label: string, value: unknown) => {
    logs.push({ label: String(label || ""), value });
  };

  const allCode = allFns.map((f) => generateCode(f, allFns).code).join("\n");
  const main = generateCode(fn, allFns);
  const argsExpr = args
    .map((a) => {
      try { return JSON.stringify(JSON.parse(a)); }
      catch { return JSON.stringify(a); }
    })
    .join(", ");

  const wrap = `
if (!window.__lastMouseEvent) {
  window.__mouseTrack = function(e) { window.__lastMouseEvent = e; };
  document.addEventListener("mousemove", window.__mouseTrack);
}
${allCode}
return (async () => { return await ${main.fnName}(${argsExpr}); })();
`;
  try {
    const factory = new Function("__log", wrap);
    const result = await factory(__log);
    return { ok: true, result, logs };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return { ok: false, error: message, logs };
  }
}

export function highlightJs(code: string): string {
  const KW = /\b(function|return|const|let|var|if|else|for|while|async|await|true|false|null|undefined|new|of|in)\b/g;
  const safe = code.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return safe
    .replace(/\/\/[^\n]*/g, (m) => `<span class="ffn-com">${m}</span>`)
    .replace(/(`[^`]*`|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')/g, (m) => `<span class="ffn-str">${m}</span>`)
    .replace(/\b(\d+(?:\.\d+)?)\b/g, '<span class="ffn-num">$1</span>')
    .replace(KW, '<span class="ffn-kw">$1</span>')
    .replace(/\b([a-zA-Z_$][\w$]*)\(/g, '<span class="ffn-fn">$1</span>(');
}

export function formatPreview(v: unknown): string {
  if (v === undefined) return "undefined";
  if (v === null) return "null";
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  try { return JSON.stringify(v); }
  catch { return String(v); }
}
